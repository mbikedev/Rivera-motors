#!/usr/bin/env node
// Generates supabase/seed.sql from the fictional demo data so the demo data source
// and the database seed never drift apart. Run: npm run db:seed:generate
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { vehicles } = JSON.parse(readFileSync(join(root, 'src/lib/data/demo/demo-vehicles.json'), 'utf8'));
const settings = JSON.parse(readFileSync(join(root, 'src/lib/data/demo/demo-settings.json'), 'utf8'));

function q(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'object') return `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

const vehicleColumns = [
  'id',
  'slug',
  'make',
  'model',
  'variant',
  'manufacture_year',
  'first_registration_date',
  'mileage_km',
  'fuel_type',
  'transmission',
  'engine_cc',
  'power_kw',
  'body_type',
  'doors',
  'seats',
  'color',
  'euro_standard',
  'co2_emissions_g_km',
  'vin_public',
  'origin_country',
  'documents_available',
  'service_history',
  'technical_inspection',
  'asking_price_eur',
  'price_on_request',
  'starts',
  'drivable',
  'missing_parts',
  'damage_assessed_at',
  'published_at',
  'created_at',
];
const translationColumns = [
  'locale',
  'title',
  'damage_summary',
  'damage_details',
  'diagnosis_notes',
  'repair_notes',
  'seo_title',
  'seo_description',
];

const out = [];
out.push('-- GENERATED by scripts/generate-seed.mjs – do not edit by hand.');
out.push('-- FICTIONAL DEMO DATA for Rivera Motors GmbH (demo). Remove before going live:');
out.push("--   delete from public.vehicles where id::text like 'a1f0c3d2-%';");
out.push('');
out.push('begin;');
out.push('');

for (const v of vehicles) {
  out.push(`-- ${v.slug}`);
  out.push(
    `insert into public.vehicles (${vehicleColumns.join(', ')}, status) values (${vehicleColumns
      .map((c) => q(v[c]))
      .join(', ')}, 'draft') on conflict (id) do nothing;`,
  );
  for (const t of v.translations) {
    out.push(
      `insert into public.vehicle_translations (vehicle_id, ${translationColumns.join(', ')}) values (${q(v.id)}, ${translationColumns
        .map((c) => q(t[c]))
        .join(', ')}) on conflict do nothing;`,
    );
  }
  const de = v.translations.find((t) => t.locale === 'de');
  if (de) {
    out.push(
      `update public.vehicles set damage_summary = ${q(de.damage_summary)}, damage_details = ${q(de.damage_details)}, diagnosis_notes = ${q(de.diagnosis_notes)}, repair_notes = ${q(de.repair_notes)}, seo_title = ${q(de.seo_title)}, seo_description = ${q(de.seo_description)} where id = ${q(v.id)};`,
    );
  }
  v.damages.forEach((d, i) => {
    out.push(
      `insert into public.vehicle_damages (vehicle_id, category, area, severity, description, translations, sort_order) values (${q(v.id)}, ${q(d.category)}, ${q(d.area)}, ${q(d.severity)}, ${q(d.description)}, ${q(d.translations ?? {})}, ${i});`,
    );
  });
  for (const m of v.media) {
    out.push(
      `insert into public.vehicle_media (vehicle_id, storage_path, media_type, alt_text, caption, is_damage_view, is_primary, sort_order) values (${q(v.id)}, ${q(m.storage_path)}, ${q(m.media_type)}, ${q(m.alt_text)}, ${q(m.caption)}, ${q(m.is_damage_view)}, ${q(m.is_primary)}, ${q(m.sort_order)});`,
    );
  }
  if (v.private) {
    out.push(
      `insert into public.vehicle_private_data (vehicle_id, vin_private, internal_notes) values (${q(v.id)}, ${q(v.private.vin_private)}, ${q(v.private.internal_notes)}) on conflict do nothing;`,
    );
  }
  if (v.status !== 'draft') {
    out.push(`update public.vehicles set status = ${q(v.status)} where id = ${q(v.id)};`);
  }
  out.push('');
}

out.push('-- Site settings (fictional demo values)');
for (const key of ['company', 'contact', 'opening_hours', 'visit', 'home', 'features', 'legal']) {
  out.push(
    `insert into public.site_settings (key, value) values (${q(key)}, ${q(settings[key])}) on conflict (key) do nothing;`,
  );
}
out.push('');
out.push('-- Seeding is not an admin action: keep the audit log clean.');
out.push('delete from public.audit_logs;');
out.push('');
out.push('commit;');
out.push('');

writeFileSync(join(root, 'supabase/seed.sql'), out.join('\n'));
console.log(`supabase/seed.sql written (${vehicles.length} vehicles)`);
